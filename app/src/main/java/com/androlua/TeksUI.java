    /**
     * Terjemahan kunci berpenanda {N} (mis. "SDK target (kosong = {N})"):
     * {N} diganti argumen. Bila kunci tidak dikenal, kunci itu
     * sendiri yang dipakai (dengan {N} tetap diganti).
     */
    public static String teksArg(String kode, String kunci, String arg) {
        String t = teks(kode, kunci);
        if (arg == null) arg = "";
        return t.replace("{N}", arg);
    }

    /**
     * Terjemahan kunci dalam bahasa kode ("es", "es-ES" -> "es").
     * Kunci itu sendiri bila kode/kunci tidak dikenal atau
     * terjemahannya kosong — layar tidak pernah kosong.
     */
    public static String teks(String kode, String kunci) {
        if (kunci == null) return "";
        int ik = indeksKunci(kunci);
        if (ik < 0) return kunci;
        int ib = indeksBahasa(kode);
        if (ib < 0) return kunci;
        String t = dataBahasa(ib)[ik];
        return (t == null || t.length() == 0) ? kunci : t;
    }

    /** Terjemahan kunci ke-i dalam bahasa kode. */
    public static String teksIndeks(String kode, int indeks) {
        if (indeks < 0 || indeks >= KUNCI.length) return "";
        return teks(kode, KUNCI[indeks]);
    }

