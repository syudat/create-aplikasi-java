    private static int indeksBahasa(String kode) {
        Bahasa.Entri e = Bahasa.dariKode(kode);
        if (e == null) return -1;
        for (int i = 0; i < KODE.length; i++) {
            if (KODE[i].equals(e.kode)) return i;
        }
        return -1;
    }

    private static int indeksKunci(String kunci) {
        if (kunci == null) return -1;
        for (int i = 0; i < KUNCI.length; i++) {
            if (KUNCI[i].equals(kunci)) return i;
        }
        return -1;
    }

